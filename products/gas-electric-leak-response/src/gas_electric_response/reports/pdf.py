"""PDF builders (reportlab). Report 1 = Field Ticket, Report 2 = Ignition & Hazard Assessment."""
from __future__ import annotations

import io
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Image, KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from ..models import HazardGrade, IncidentContext
from .maps import GRADE_FILL, render_risk_map

SS = getSampleStyleSheet()
H1 = ParagraphStyle("H1", parent=SS["Heading1"], fontSize=16, spaceAfter=4)
H2 = ParagraphStyle("H2", parent=SS["Heading2"], fontSize=11, spaceBefore=8, spaceAfter=3)
BODY = ParagraphStyle("B", parent=SS["BodyText"], fontSize=9, leading=11)
SMALL = ParagraphStyle("S", parent=BODY, fontSize=7.5, leading=9, textColor=colors.HexColor("#555555"))
DISCLAIMER = ("Screening-level decision support generated by automation. The plume envelope is a heuristic, not a validated "
              "dispersion model, and the valve list is nearest-valve, not a traced upstream isolation plan. It does not replace "
              "emergency response procedures, field judgement, or engineering review.")


def _tbl(rows, widths, header=True):
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    st = [("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#bbbbbb")),
          ("VALIGN", (0, 0), (-1, -1), "TOP")]
    if header:
        st += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e9eef4")), ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold")]
    t.setStyle(TableStyle(st))
    return t


def _p(text) -> Paragraph:
    return Paragraph(str(text).replace("&", "&amp;").replace("<", "&lt;"), BODY)


def _fmt(v, nd=1, unit=""):
    return "n/a" if v is None else f"{v:.{nd}f}{unit}"


class _Base:
    def __init__(self, tz: str):
        self.tz = ZoneInfo(tz)

    def local(self, dt: datetime) -> str:
        return dt.astimezone(self.tz).strftime("%Y-%m-%d %H:%M:%S %Z")

    def _doc(self, title: str) -> tuple[io.BytesIO, SimpleDocTemplate]:
        buf = io.BytesIO()
        return buf, SimpleDocTemplate(buf, pagesize=letter, leftMargin=0.6 * inch, rightMargin=0.6 * inch, topMargin=0.6 * inch,
                                      bottomMargin=0.6 * inch, title=title, author="gas-electric-leak-response")


class FieldTicketPDF(_Base):
    """Report 1: the technician's original inputs, readings, photos, badge and timestamps."""

    def build(self, ctx: IncidentContext, generated_at: datetime) -> bytes:
        r = ctx.report
        buf, doc = self._doc(f"Field Ticket {r.leak_id}")
        s = [Paragraph(f"Gas Leak Field Ticket - {r.leak_id}", H1),
             Paragraph("Compliance record of the field submission (original technician inputs; not re-interpreted).", SMALL), Spacer(1, 6)]
        rows = [["Field", "Value"],
                ["Leak ID", r.leak_id], ["Crew badge", r.crew_badge or "n/a"],
                ["Submitted (local)", self.local(r.reported_at)], ["Submitted (UTC)", r.reported_at.strftime("%Y-%m-%d %H:%M:%S UTC")],
                ["Record generated (local)", self.local(generated_at)],
                ["Location (lat, lon)", f"{r.lat:.6f}, {r.lon:.6f}"],
                ["Gas reading", f"{_fmt(r.lel_pct)} % LEL   |   {_fmt(r.ppm, 0)} ppm"],
                ["Pipeline type (as normalized)", r.pipeline_type], ["Pressure class", r.pressure_class],
                ["Surface cover", r.surface_cover], ["Instrument temp (C)", _fmt(r.temp_c)],
                ["Source GlobalID / ObjectID", f"{r.source_global_id} / {r.source_object_id}"]]
        s += [_tbl([[_p(c) for c in row] for row in rows], [2.0 * inch, 5.2 * inch]), Paragraph("Technician notes", H2), _p(r.notes or "(none)")]
        if ctx.is_duplicate:
            s += [Paragraph("Duplicate reading", H2), _p(f"Flagged as a repeat reading of {ctx.duplicate_of} (within 50 ft / 12 h).")]
        if ctx.flags:
            s += [Paragraph("Data-quality flags", H2), _p("; ".join(ctx.flags))]
        s.append(Paragraph("Inspection photos / instrument screenshots", H2))
        if not r.photos:
            s.append(_p("No photo attachments were found on the submission."))
        for pth in r.photos:
            try:
                from PIL import Image as PILImage  # reportlab depends on pillow

                with PILImage.open(pth) as im:
                    w, h = im.size
                k = min(3.4 * inch / w, 3.0 * inch / h)
                s.append(KeepTogether([Image(pth, width=w * k, height=h * k), Paragraph(Path(pth).name, SMALL)]))
            except Exception:   # unreadable image: list it instead of failing the whole record
                s.append(_p(f"(could not embed {Path(pth).name})"))
        s += [Spacer(1, 8), Paragraph("Raw submitted attributes", H2),
              _tbl([["Attribute", "Value"]] + [[_p(k), _p(v)] for k, v in sorted(r.raw_attributes.items())], [2.4 * inch, 4.8 * inch])]
        doc.build(s)
        return buf.getvalue()


class RiskAssessmentPDF(_Base):
    """Report 2: plume map, electric assets at risk, meters, valves, HSI."""

    def build(self, ctx: IncidentContext, generated_at: datetime) -> bytes:
        r = ctx.report
        buf, doc = self._doc(f"Joint Hazard Assessment {r.leak_id}")
        g = ctx.grade
        banner = Table([[Paragraph(f"<b>Grade {int(g)} - {g.label.upper()}</b>", ParagraphStyle("x", parent=BODY, fontSize=13, textColor=colors.white))]],
                       colWidths=[7.2 * inch])
        banner.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(GRADE_FILL[int(g)])), ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
        s = [Paragraph(f"Ignition & Hazard Assessment - {r.leak_id}", H1),
             Paragraph(f"Generated {self.local(generated_at)}  |  Dispatch: {ctx.dispatch_code}", SMALL), Spacer(1, 4), banner,
             Paragraph("Why this grade", H2), _p("; ".join(ctx.grade_reasons))]
        if ctx.is_escalation:
            s += [_p(f"ESCALATION: this reading grades worse than the earlier report {ctx.duplicate_of}.")]
        s += [Spacer(1, 4), Image(io.BytesIO(render_risk_map(ctx)), width=6.4 * inch, height=5.3 * inch)]
        w = ctx.weather
        s += [Paragraph("Atmospheric conditions", H2),
              _p("Weather unavailable - a conservative omnidirectional envelope was used." if not w else
                 f"Wind {_fmt(w.wind_speed_mps)} m/s from {_fmt(w.wind_from_deg, 0)} deg | {_fmt(w.air_temp_c)} C | {_fmt(w.pressure_hpa, 0)} hPa | "
                 f"station {w.station or 'n/a'} | observed {self.local(w.observed_at) if w.observed_at else 'n/a'} | status {w.status}")]
        s.append(Paragraph("Electric assets inside the plume", H2))
        if ctx.electric_hits:
            rows = [["Asset", "Type", "Risk class", "Distance (m)", "Energized"]] + [
                [h.asset_id, h.asset_type, h.category.replace("_", " "), f"{h.distance_m:.1f}", "n/a" if h.energized is None else ("yes" if h.energized else "no")]
                for h in ctx.electric_hits[:30]]
            s.append(_tbl([[_p(c) for c in row] for row in rows], [1.4 * inch, 1.8 * inch, 1.4 * inch, 1.0 * inch, 1.0 * inch]))
            if len(ctx.electric_hits) > 30:
                s.append(_p(f"... and {len(ctx.electric_hits) - 30} more (see layer)."))
        else:
            s.append(_p("None found inside the plume envelope."))
        s += [Paragraph("Critical facilities / customers", H2),
              _p("; ".join(f"{h.name or h.asset_id} ({h.asset_type}, {h.distance_m:.0f} m)" for h in ctx.facility_hits) or "No critical facilities inside the plume."),
              _p(f"Customer meters inside the plume: {ctx.meter_count}")]
        s.append(Paragraph("Recommended gas shutoff valves (nearest, to be confirmed by operations)", H2))
        s.append(_tbl([[_p(c) for c in row] for row in [["#", "Valve ID", "Distance (m)"]] + [[i, v.valve_id, f"{v.distance_m:.0f}"] for i, v in enumerate(ctx.valves, 1)]],
                      [0.5 * inch, 3.0 * inch, 1.5 * inch]) if ctx.valves else _p("No valves found within the search radius."))
        s.append(Paragraph("811 excavation tickets within 500 ft", H2))
        s.append(_tbl([[_p(c) for c in row] for row in [["Ticket", "Status", "Work type", "Distance (m)"]] +
                       [[t.number, t.status, t.work_type, _fmt(t.distance_m, 0)] for t in ctx.tickets]], [1.6 * inch, 1.4 * inch, 2.4 * inch, 1.2 * inch])
                 if ctx.tickets else _p("None reported (or 811 lookup not configured / failed - see flags)."))
        s += [Paragraph("Model assumptions and flags", H2), _p("; ".join(ctx.plume.assumptions + ctx.flags) or "none"),
              Spacer(1, 6), Paragraph(DISCLAIMER, SMALL)]
        doc.build(s)
        return buf.getvalue()
